package main

import (
	"cmp"
	"fmt"
	"go/format"
	"maps"
	"slices"
	"strings"

	"github.com/stubbedev/tilde/internal/wire"
)

type side int

const (
	serverSide side = iota
	clientSide
)

var sides = []side{serverSide, clientSide}

func (s side) dir() string {
	if s == serverSide {
		return "server"
	}
	return "client"
}

type gen struct {
	b        strings.Builder
	p        *protocol
	s        side
	imports  map[*protocol]bool
	declared map[string]bool
	errs     []error
}

func sortedProtocols(set map[*protocol]bool) []*protocol {
	return slices.SortedFunc(maps.Keys(set), func(a, b *protocol) int { return cmp.Compare(a.pkg, b.pkg) })
}

func generate(p *protocol, s side, module string) ([]byte, error) {
	g := &gen{p: p, s: s, imports: map[*protocol]bool{}, declared: map[string]bool{}}
	for _, i := range p.interfaces {
		g.iface(i)
	}
	if len(g.errs) > 0 {
		return nil, fmt.Errorf("%s (%s): %w", p.file, s.dir(), g.errs[0])
	}
	var out strings.Builder
	fmt.Fprintf(&out, "// Code generated by internal/scanner from %s; DO NOT EDIT.\n\npackage %s\n\nimport (\n", p.file, p.pkg)
	fmt.Fprintf(&out, "\t%q\n", module+"/internal/wire")
	for _, d := range sortedProtocols(g.imports) {
		fmt.Fprintf(&out, "\t%q\n", module+"/internal/protocol/"+s.dir()+"/"+d.pkg)
	}
	out.WriteString(")\n")
	out.WriteString(g.b.String())
	src, err := format.Source([]byte(out.String()))
	if err != nil {
		return nil, fmt.Errorf("%s (%s): format generated code: %w", p.file, s.dir(), err)
	}
	return src, nil
}

func (g *gen) printf(format string, args ...any) {
	fmt.Fprintf(&g.b, format, args...)
}

func (g *gen) declare(names ...string) {
	for _, n := range names {
		if g.declared[n] {
			g.errs = append(g.errs, fmt.Errorf("generated identifier %s is declared twice", n))
		}
		g.declared[n] = true
	}
}

func (g *gen) incoming(i *iface) []*message {
	if g.s == serverSide {
		return i.requests
	}
	return i.events
}

func (g *gen) outgoing(i *iface) []*message {
	if g.s == serverSide {
		return i.events
	}
	return i.requests
}

func (g *gen) incomingField() string {
	if g.s == serverSide {
		return "Requests"
	}
	return "Events"
}

func (g *gen) hasHandler(i *iface) bool {
	return len(g.incoming(i)) > 0
}

func (g *gen) qualify(p *protocol, name string) string {
	if p == g.p {
		return name
	}
	g.imports[p] = true
	return p.pkg + "." + name
}

func (g *gen) typeRef(i *iface) string {
	return g.qualify(i.proto, i.goName)
}

func (g *gen) enumRef(e *enum) string {
	return g.qualify(e.owner.proto, e.goName)
}

func newIDArg(m *message) *arg {
	for _, a := range m.args {
		if a.typ == wire.ArgNewID {
			return a
		}
	}
	return nil
}

func (g *gen) iface(i *iface) {
	g.declare(i.goName, i.goName+"Interface", "Create"+i.goName, "New"+i.goName)
	g.metadata(i)
	for _, e := range i.enums {
		g.enum(e)
	}
	if g.hasHandler(i) {
		g.declare(i.goName + "Handler")
		g.printf("\ntype %sHandler interface {\n", i.goName)
		for _, m := range g.incoming(i) {
			g.printf("\t%s\n", g.handlerSignature(i, m))
		}
		g.printf("}\n")
	}
	g.object(i)
	g.dispatch(i)
	for _, m := range g.outgoing(i) {
		g.send(i, m)
	}
	if g.s == serverSide {
		for _, e := range i.enums {
			if e.name == "error" {
				g.printf("\nfunc (obj *%s) ProtocolError(code %s, message string) error {\n", i.goName, e.goName)
				g.printf("\treturn &wire.ProtocolError{Object: obj.object.ID(), Code: uint32(code), Message: message}\n}\n")
			}
		}
	}
}

func (g *gen) metadata(i *iface) {
	g.printf("\nvar %sInterface = &wire.Interface{\n\tName: %q,\n\tVersion: %d,\n", i.goName, i.name, i.version)
	g.specs("Requests", i.requests)
	g.specs("Events", i.events)
	g.printf("}\n")
}

func (g *gen) specs(field string, ms []*message) {
	if len(ms) == 0 {
		return
	}
	g.printf("\t%s: []wire.MessageSpec{\n", field)
	for _, m := range ms {
		g.printf("\t\t{Name: %q, Since: %d", m.name, m.since)
		if m.destructor {
			g.printf(", Destructor: true")
		}
		if len(m.args) > 0 {
			g.printf(", Args: []wire.Arg{")
			for _, a := range m.args {
				g.printf("{Name: %q, Type: wire.%s", a.name, argConstants[a.typ])
				if a.ifaceRef != "" {
					g.printf(", Interface: %q", a.ifaceRef)
				}
				if a.nullable {
					g.printf(", Nullable: true")
				}
				g.printf("}, ")
			}
			g.printf("}")
		}
		g.printf("},\n")
	}
	g.printf("\t},\n")
}

func (g *gen) enum(e *enum) {
	g.printf("\ntype %s uint32\n\nconst (\n", e.goName)
	g.declare(e.goName)
	for _, en := range e.entries {
		g.declare(en.goName)
		g.printf("\t%s %s = %d\n", en.goName, e.goName, en.value)
	}
	g.printf(")\n")
	if e.bitfield {
		g.printf("\nfunc (v %s) Has(flag %s) bool {\n\treturn v&flag == flag\n}\n", e.goName, e.goName)
	}
}

func (g *gen) valueType(a *arg) string {
	if a.enum != nil {
		return g.enumRef(a.enum)
	}
	switch a.typ {
	case wire.ArgInt:
		return "int32"
	case wire.ArgUint:
		return "uint32"
	case wire.ArgFixed:
		return "wire.Fixed"
	case wire.ArgString:
		if a.nullable {
			return "*string"
		}
		return "string"
	case wire.ArgObject:
		if a.iface == nil {
			return "wire.Resource"
		}
		return "*" + g.typeRef(a.iface)
	case wire.ArgArray:
		return "[]byte"
	case wire.ArgFD:
		return "int"
	}
	panic("scanner: no value type for " + a.name)
}

func (g *gen) handlerSignature(i *iface, m *message) string {
	params := []string{"obj *" + i.goName}
	for _, a := range m.args {
		switch {
		case a.typ == wire.ArgNewID && a.iface == nil:
			params = append(params, a.goName+"Interface string", a.goName+"Version uint32", a.goName+" wire.ObjectID")
		case a.typ == wire.ArgNewID:
			params = append(params, a.goName+" *"+g.typeRef(a.iface))
		default:
			params = append(params, a.goName+" "+g.valueType(a))
		}
	}
	result := "error"
	if child := newIDArg(m); child != nil && child.iface != nil && g.hasHandler(child.iface) {
		result = "(" + g.typeRef(child.iface) + "Handler, error)"
	}
	return fmt.Sprintf("%s(%s) %s", m.goName, strings.Join(params, ", "), result)
}

func (g *gen) object(i *iface) {
	g.printf("\ntype %s struct {\n\tobject wire.Object\n", i.goName)
	if g.hasHandler(i) {
		g.printf("\thandler %sHandler\n", i.goName)
	}
	g.printf("}\n")
	g.printf("\nfunc (obj *%s) Base() *wire.Object {\n\treturn &obj.object\n}\n", i.goName)
	if g.hasHandler(i) {
		g.printf("\nfunc (obj *%s) Handler() %sHandler {\n\treturn obj.handler\n}\n", i.goName, i.goName)
	}
	g.printf("\nfunc Create%[1]s(p wire.Peer, id wire.ObjectID, version uint32", i.goName)
	if g.hasHandler(i) {
		g.printf(", newHandler func(*%[1]s) (%[1]sHandler, error)", i.goName)
	}
	g.printf(") (*%[1]s, error) {\n", i.goName)
	g.printf("\tobject, err := wire.NewObject(p, id, version, %[1]sInterface)\n\tif err != nil {\n\t\treturn nil, err\n\t}\n", i.goName)
	g.printf("\tobj := &%s{object: object}\n\tif err := p.Add(obj); err != nil {\n\t\treturn nil, err\n\t}\n", i.goName)
	if g.hasHandler(i) {
		g.printf("\th, err := newHandler(obj)\n\tif err != nil {\n\t\treturn nil, err\n\t}\n")
		g.printf("\tif h == nil {\n\t\treturn nil, wire.NoHandler(%sInterface)\n\t}\n\tobj.handler = h\n", i.goName)
	}
	g.printf("\treturn obj, nil\n}\n")
	params := []string{"p wire.Peer"}
	if g.s == serverSide {
		params = append(params, "id wire.ObjectID")
	}
	params = append(params, "version uint32")
	if g.hasHandler(i) {
		params = append(params, "h "+i.goName+"Handler")
	}
	g.printf("\nfunc New%s(%s) (*%s, error) {\n", i.goName, strings.Join(params, ", "), i.goName)
	if g.hasHandler(i) {
		g.printf("\tif h == nil {\n\t\treturn nil, wire.NoHandler(%sInterface)\n\t}\n", i.goName)
	}
	g.printf("\tif err := wire.CheckVersion(%sInterface, version); err != nil {\n\t\treturn nil, err\n\t}\n", i.goName)
	if g.s == clientSide {
		g.printf("\tid, err := p.NewID()\n\tif err != nil {\n\t\treturn nil, err\n\t}\n")
	}
	g.printf("\treturn Create%s(p, id, version%s)\n}\n", i.goName, g.constantHandler(i, "h"))
}

func (g *gen) constantHandler(i *iface, h string) string {
	if !g.hasHandler(i) {
		return ""
	}
	t := g.typeRef(i)
	return fmt.Sprintf(", func(*%s) (%sHandler, error) {\n\t\treturn %s, nil\n\t}", t, t, h)
}

func (g *gen) dispatch(i *iface) {
	g.printf("\nfunc (obj *%s) Dispatch(msg *wire.Message) error {\n", i.goName)
	g.printf("\tswitch obj.object.Expect(msg, %sInterface.%s) {\n", i.goName, g.incomingField())
	for _, m := range g.incoming(i) {
		g.printf("\tcase %d:\n", m.opcode)
		g.receive(m)
	}
	g.printf("\t}\n\treturn msg.Finish()\n}\n")
}

func (g *gen) receive(m *message) {
	var call []string
	for _, a := range m.args {
		n := a.goName
		switch a.typ {
		case wire.ArgInt, wire.ArgUint:
			switch {
			case a.enum != nil:
				g.printf("\t\t%s := %s(msg.Uint())\n", n, g.enumRef(a.enum))
			case a.typ == wire.ArgInt:
				g.printf("\t\t%s := msg.Int()\n", n)
			default:
				g.printf("\t\t%s := msg.Uint()\n", n)
			}
		case wire.ArgFixed:
			g.printf("\t\t%s := msg.Fixed()\n", n)
		case wire.ArgString:
			if a.nullable {
				g.printf("\t\tvar %s *string\n\t\tif v, ok := msg.OptStr(); ok {\n\t\t\t%s = &v\n\t\t}\n", n, n)
			} else {
				g.printf("\t\t%s := msg.Str()\n", n)
			}
		case wire.ArgObject:
			g.printf("\t\t%s := wire.ObjectArg[%s](msg, obj.object.Peer(), %t)\n", n, g.valueType(a), a.nullable)
		case wire.ArgNewID:
			if a.iface == nil {
				g.printf("\t\t%[1]sInterface := msg.Str()\n\t\t%[1]sVersion := msg.Uint()\n\t\t%[1]s := msg.NewID()\n", n)
				call = append(call, n+"Interface", n+"Version")
			} else {
				g.printf("\t\t%sID := msg.NewID()\n", n)
			}
		case wire.ArgArray:
			g.printf("\t\t%s := msg.Array()\n", n)
		case wire.ArgFD:
			g.printf("\t\t%s := msg.FD()\n", n)
		}
		call = append(call, n)
	}
	g.printf("\t\tif err := msg.Finish(); err != nil {\n\t\t\treturn err\n\t\t}\n")
	var fds []string
	for _, a := range m.args {
		if a.typ == wire.ArgFD {
			fds = append(fds, a.goName)
		}
	}
	child := newIDArg(m)
	invoke := fmt.Sprintf("obj.handler.%s(%s)", m.goName, strings.Join(append([]string{"obj"}, call...), ", "))
	switch {
	case child != nil && child.iface != nil && g.hasHandler(child.iface) && len(fds) > 0:
		t := g.typeRef(child.iface)
		g.printf("\t\thandled := false\n")
		g.printf("\t\t_, err := %s(obj.object.Peer(), %sID, obj.object.Version(), func(%s *%s) (%sHandler, error) {\n", g.qualify(child.iface.proto, "Create"+child.iface.goName), child.goName, child.goName, t, t)
		g.printf("\t\t\thandled = true\n\t\t\treturn %s\n\t\t})\n", invoke)
		g.printf("\t\tif !handled {\n\t\t\treturn wire.CloseUnclaimed(err, %s)\n\t\t}\n\t\treturn err\n", strings.Join(fds, ", "))
	case child != nil && child.iface != nil && g.hasHandler(child.iface):
		t := g.typeRef(child.iface)
		g.printf("\t\t_, err := %s(obj.object.Peer(), %sID, obj.object.Version(), func(%s *%s) (%sHandler, error) {\n", g.qualify(child.iface.proto, "Create"+child.iface.goName), child.goName, child.goName, t, t)
		g.printf("\t\t\treturn %s\n\t\t})\n\t\treturn err\n", invoke)
	case child != nil && child.iface != nil:
		fail := "return err"
		if len(fds) > 0 {
			fail = "return wire.CloseUnclaimed(err, " + strings.Join(fds, ", ") + ")"
		}
		g.printf("\t\t%[1]s, err := %[2]s(obj.object.Peer(), %[1]sID, obj.object.Version())\n\t\tif err != nil {\n\t\t\t%[3]s\n\t\t}\n", child.goName, g.qualify(child.iface.proto, "Create"+child.iface.goName), fail)
		g.printf("\t\treturn %s\n", invoke)
	case m.destructor:
		g.printf("\t\tif err := %s; err != nil {\n\t\t\treturn err\n\t\t}\n", invoke)
		g.printf("\t\treturn obj.object.Peer().Remove(obj.object.ID())\n")
	default:
		g.printf("\t\treturn %s\n", invoke)
	}
}

func (g *gen) send(i *iface, m *message) {
	name := m.goName
	if g.s == serverSide {
		name = "Send" + name
	}
	child := newIDArg(m)
	creates := child != nil && child.iface != nil
	var params []string
	for _, a := range m.args {
		switch {
		case a.typ == wire.ArgNewID && a.iface == nil:
			params = append(params, a.goName+" wire.Resource")
		case a.typ == wire.ArgNewID:
			if g.hasHandler(a.iface) {
				params = append(params, "h "+g.typeRef(a.iface)+"Handler")
			}
		default:
			params = append(params, a.goName+" "+g.valueType(a))
		}
	}
	fail := "return err"
	result := "error"
	if creates {
		fail = "return nil, err"
		result = "(*" + g.typeRef(child.iface) + ", error)"
	}
	failWith := func(expr string) string { return strings.Replace(fail, "err", expr, 1) }
	g.printf("\nfunc (obj *%s) %s(%s) %s {\n", i.goName, name, strings.Join(params, ", "), result)
	if m.since > 1 {
		g.printf("\tif err := obj.object.Require(%q, %d); err != nil {\n\t\t%s\n\t}\n", m.name, m.since, fail)
	}
	for _, a := range m.args {
		if a.typ != wire.ArgObject && (a.typ != wire.ArgNewID || a.iface != nil) {
			continue
		}
		owns := fmt.Sprintf("if err := obj.object.Owns(%s); err != nil {\n\t\t%s\n\t}\n", a.goName, fail)
		if a.nullable {
			g.printf("\tif %s != nil {\n\t\t%s\t}\n", a.goName, owns)
			continue
		}
		g.printf("\tif %s == nil {\n\t\t%s\n\t}\n\t%s", a.goName, failWith(fmt.Sprintf("obj.object.NullArg(%q, %q)", m.name, a.name)), owns)
	}
	if creates {
		if g.hasHandler(child.iface) {
			g.printf("\tif h == nil {\n\t\treturn nil, wire.NoHandler(%s)\n\t}\n", g.qualify(child.iface.proto, child.iface.goName+"Interface"))
		}
		g.printf("\tchildID, err := obj.object.Peer().NewID()\n\tif err != nil {\n\t\treturn nil, err\n\t}\n")
		g.printf("\tchild, err := %s(obj.object.Peer(), childID, obj.object.Version()%s)\n\tif err != nil {\n\t\treturn nil, err\n\t}\n", g.qualify(child.iface.proto, "Create"+child.iface.goName), g.constantHandler(child.iface, "h"))
	}
	g.printf("\tenc := obj.object.Begin(%d)\n", m.opcode)
	for _, a := range m.args {
		g.encode(a)
	}
	g.printf("\tif err := enc.End(); err != nil {\n\t\t%s\n\t}\n", fail)
	if m.destructor {
		g.printf("\tif err := obj.object.Peer().Remove(obj.object.ID()); err != nil {\n\t\t%s\n\t}\n", fail)
	}
	if creates {
		g.printf("\treturn child, nil\n}\n")
	} else {
		g.printf("\treturn nil\n}\n")
	}
}

func (g *gen) encode(a *arg) {
	n := a.goName
	switch a.typ {
	case wire.ArgInt:
		if a.enum != nil {
			g.printf("\tenc.Uint(uint32(%s))\n", n)
		} else {
			g.printf("\tenc.Int(%s)\n", n)
		}
	case wire.ArgUint:
		if a.enum != nil {
			g.printf("\tenc.Uint(uint32(%s))\n", n)
		} else {
			g.printf("\tenc.Uint(%s)\n", n)
		}
	case wire.ArgFixed:
		g.printf("\tenc.Fixed(%s)\n", n)
	case wire.ArgString:
		if a.nullable {
			g.printf("\tif %[1]s == nil {\n\t\tenc.NullStr()\n\t} else {\n\t\tenc.Str(*%[1]s)\n\t}\n", n)
		} else {
			g.printf("\tenc.Str(%s)\n", n)
		}
	case wire.ArgObject:
		if a.nullable {
			g.printf("\tif %[1]s == nil {\n\t\tenc.Object(0)\n\t} else {\n\t\tenc.Object(%[1]s.Base().ID())\n\t}\n", n)
		} else {
			g.printf("\tenc.Object(%s.Base().ID())\n", n)
		}
	case wire.ArgNewID:
		if a.iface == nil {
			g.printf("\tenc.Str(%[1]s.Base().Interface().Name)\n\tenc.Uint(%[1]s.Base().Version())\n\tenc.Object(%[1]s.Base().ID())\n", n)
		} else {
			g.printf("\tenc.Object(childID)\n")
		}
	case wire.ArgArray:
		g.printf("\tenc.Array(%s)\n", n)
	case wire.ArgFD:
		g.printf("\tenc.FD(%s)\n", n)
	}
}
